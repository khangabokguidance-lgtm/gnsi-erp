// buildCbtSetup.mjs — writes supabase/cbt_online_setup.sql: every online-exam migration (20261034 … latest) in one
// script that can be pasted into Supabase → SQL editor, on an empty database OR on top of any earlier state, and
// re-run safely. Run after adding a new CBT migration:   node tools/buildCbtSetup.mjs
import fs from 'node:fs'
const dir = 'supabase/migrations'
const files = fs.readdirSync(dir).filter(f => /^2026103[4-9]_cbt_|^202610[4-9]\d_cbt_/.test(f)).sort()
const head = `-- ═══════════════════════════════════════════════════════════════════════════════════════════
-- CBT online exam — complete database setup (generated by tools/buildCbtSetup.mjs; do not edit by hand).
-- Paste ALL of this into Supabase → SQL editor → Run. It works on an empty database and on top of any earlier
-- partial run, and can be run again after an update. Contents, in order:
${files.map(f => `--   ${f}`).join('\n')}
-- Needs the Students module's tables (public.students) and the helper public.qbank_is_staff() to exist already.
-- ═══════════════════════════════════════════════════════════════════════════════════════════

-- Newer function versions are dropped first so older scripts below can be replayed without a name clash;
-- the later scripts then recreate the final versions.
drop function if exists public.cbt_start(text, text, text, text, text);
drop function if exists public.cbt_lookup(text, text, text, text);
drop function if exists public.cbt_resume(text, text, text);
drop function if exists public.cbt_submit(text, text, jsonb, jsonb, int, text);
drop function if exists public.cbt_save(text, text, jsonb, jsonb, int, text, int, text);

`
const body = files.map(f => `-- ───── ${f} ─────\n${fs.readFileSync(`${dir}/${f}`, 'utf8').trim()}\n`).join('\n')
fs.writeFileSync('supabase/cbt_online_setup.sql', `${head}${body}\n-- make the API pick up the new functions straight away\nnotify pgrst, 'reload schema';\n`)
console.log(`wrote supabase/cbt_online_setup.sql from ${files.length} migrations`)
